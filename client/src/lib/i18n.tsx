export const DICTS: Record<Lang, Dict> = { ms, en };

export type TFn = (key: string, vars?: Record<string, string | number>) => string;

interface I18nValue {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: TFn;
  fmt: Format;
}

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => (load('afm.lang') === 'en' ? 'en' : 'ms'));
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    save('afm.lang', l);
  }, []);
  useEffect(() => {
    document.documentElement.setAttribute('lang', lang);
  }, [lang]);
  const value = useMemo<I18nValue>(() => {
    const dict = DICTS[lang];
    const t: TFn = (key, vars) => {
      let s = dict[key];
      if (s === undefined) {
        if (import.meta.env.DEV) console.warn(`[i18n] missing key "${key}" (${lang})`);
        s = key;
      }
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
      return s;
    };
    return { lang, setLang, t, fmt: makeFormat(lang) };
  }, [lang, setLang]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const v = useContext(I18nContext);
  if (!v) throw new Error('useI18n must be used inside I18nProvider');
  return v;
}
